"""Ownership scoring: turns per-author line counts into a risk score per file.

Approach (see issue #4 for v1):
  - Every commit's lines are weighted by how recent the commit is, halving
    every HALF_LIFE_DAYS. Someone who rewrote a file last month counts for
    more than someone who wrote it three years ago, so the score reflects who
    understands the file today, not who wrote it first.
  - An author's share of a file = their weighted lines / all weighted lines.
  - A file's risk score = its top author's share (0 to 1, higher = riskier).
  - The unweighted (all-time) share is kept alongside, so the dashboard can
    show how much the decay changed the picture.

Age is measured from the newest commit being scored, not from today. Shares
are ratios, so this doesn't change them; it just keeps the weights near 1.

Known limitations:
  - Measures lines added over the file's history, not who wrote the lines
    that exist today (that would need `git blame`).
  - Authors are matched by email, so one person using two emails counts as two.
  - Decay re-balances shares but can't tell that a whole file has gone
    untouched for years; `last_changed_at` is reported for that instead.

This module is pure Python (no database, no web code) so it is easy to test.
"""

import datetime
from collections import defaultdict
from dataclasses import dataclass

# A commit this many days older than the newest one counts half as much.
HALF_LIFE_DAYS = 180

# Files that are generated by tools rather than written by people. Their line
# counts would make them look like the riskiest files, so they are skipped.
IGNORED_FILE_NAMES = {
    "package-lock.json",
    "yarn.lock",
    "pnpm-lock.yaml",
    "poetry.lock",
    "Pipfile.lock",
    "Cargo.lock",
    "go.sum",
}


@dataclass(frozen=True)
class Contribution:
    """Lines one author added to one file in one commit (one database row)."""

    file_path: str
    author_email: str
    author_name: str
    lines_added: int
    committed_at: datetime.datetime


@dataclass(frozen=True)
class AuthorShare:
    """One author's share of a file, from 0 to 1.

    `share` is recency-weighted (what the risk score uses); `historical_share`
    counts every line equally regardless of age.
    """

    name: str
    share: float
    historical_share: float
    commit_count: int
    last_commit_at: datetime.datetime


@dataclass(frozen=True)
class FileOwnership:
    """Scoring result for one file. `authors` is sorted largest share first."""

    path: str
    risk_score: float
    top_author: str
    top_author_share: float
    last_changed_at: datetime.datetime
    authors: list[AuthorShare]


def normalize_path(path: str) -> str:
    """Use "/" separators so paths look the same whichever OS ingested them."""
    return path.replace("\\", "/")


def is_ignored_file(path: str) -> bool:
    """True for generated files (e.g. lock files) that should not be scored."""
    file_name = path.rsplit("/", 1)[-1]
    return file_name in IGNORED_FILE_NAMES


def is_bot(author_name: str, author_email: str) -> bool:
    """True for automated accounts such as "dependabot[bot]"."""
    return "[bot]" in author_name or "[bot]" in author_email


def decay_weight(
    committed_at: datetime.datetime,
    newest: datetime.datetime,
    half_life_days: float = HALF_LIFE_DAYS,
) -> float:
    """How much a commit counts: 1 for the newest, 0.5 one half-life older, etc."""
    age_days = max((newest - committed_at).total_seconds() / 86400, 0)
    return 0.5 ** (age_days / half_life_days)


@dataclass
class _AuthorTotals:
    """Running totals for one author on one file while scoring."""

    lines: int = 0
    weighted_lines: float = 0.0
    commit_count: int = 0
    last_commit_at: datetime.datetime | None = None


def score_files(
    contributions: list[Contribution], half_life_days: float = HALF_LIFE_DAYS
) -> list[FileOwnership]:
    """Compute ownership and risk for every file, riskiest first.

    Skips generated files, bot authors, and files with no lines added.
    """
    rows = [
        row
        for row in contributions
        if not is_ignored_file(normalize_path(row.file_path))
        and not is_bot(row.author_name, row.author_email)
    ]
    if not rows:
        return []

    newest = max(row.committed_at for row in rows)

    # totals_by_file[path][email] = that author's totals for the file
    totals_by_file: dict[str, dict[str, _AuthorTotals]] = defaultdict(
        lambda: defaultdict(_AuthorTotals)
    )

    # An email can appear with several names (e.g. "haradeep1" and
    # "Haradeep Puneti"). Show the name used for the most lines.
    lines_by_email_and_name: dict[str, dict[str, int]] = defaultdict(lambda: defaultdict(int))

    for row in rows:
        email = row.author_email.lower()
        totals = totals_by_file[normalize_path(row.file_path)][email]
        totals.lines += row.lines_added
        totals.weighted_lines += row.lines_added * decay_weight(
            row.committed_at, newest, half_life_days
        )
        totals.commit_count += 1
        if totals.last_commit_at is None or row.committed_at > totals.last_commit_at:
            totals.last_commit_at = row.committed_at
        lines_by_email_and_name[email][row.author_name] += row.lines_added

    display_name = {
        email: max(names, key=names.get) for email, names in lines_by_email_and_name.items()
    }

    results = []
    for path, totals_by_email in totals_by_file.items():
        total_lines = sum(t.lines for t in totals_by_email.values())
        total_weighted = sum(t.weighted_lines for t in totals_by_email.values())
        if total_lines == 0:
            continue  # e.g. binary files, which have no line counts

        authors = sorted(
            (
                AuthorShare(
                    name=display_name[email],
                    share=t.weighted_lines / total_weighted,
                    historical_share=t.lines / total_lines,
                    commit_count=t.commit_count,
                    last_commit_at=t.last_commit_at,
                )
                for email, t in totals_by_email.items()
                if t.lines > 0
            ),
            key=lambda author: author.share,
            reverse=True,
        )
        top = authors[0]
        results.append(
            FileOwnership(
                path=path,
                risk_score=top.share,
                top_author=top.name,
                top_author_share=top.share,
                # Includes commits that only removed lines: they still touched the file.
                last_changed_at=max(t.last_commit_at for t in totals_by_email.values()),
                authors=authors,
            )
        )

    return sorted(results, key=lambda file: file.risk_score, reverse=True)
