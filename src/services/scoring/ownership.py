"""Ownership scoring: turns per-author line counts into a risk score per file.

v1 approach (simple on purpose, see issue #4):
  - An author's share of a file = lines they added to it / all lines added to it.
  - A file's risk score = its top author's share (0 to 1, higher = riskier).

Known limitations:
  - Measures lines added over the file's history, not who wrote the lines
    that exist today (that would need `git blame`).
  - Authors are matched by email, so one person using two emails counts as two.

This module is pure Python (no database, no web code) so it is easy to test.
"""

from collections import defaultdict
from dataclasses import dataclass

# Files that are generated by tools rather than written by people. Their line
# counts would make them look like the riskiest files, so they are skipped.
IGNORED_FILE_NAMES = {
    "package-lock.json",
    "yarn.lock",
    "pnpm-lock.yaml",
    "poetry.lock",
    "Pipfile.lock",
    "Cargo.lock",
    "go.sum",
}


@dataclass(frozen=True)
class Contribution:
    """Lines one author added to one file (one row from the database query)."""

    file_path: str
    author_email: str
    author_name: str
    lines_added: int


@dataclass(frozen=True)
class AuthorShare:
    """One author's share of a file, from 0 to 1."""

    name: str
    share: float


@dataclass(frozen=True)
class FileOwnership:
    """Scoring result for one file. `authors` is sorted largest share first."""

    path: str
    risk_score: float
    top_author: str
    top_author_share: float
    authors: list[AuthorShare]


def normalize_path(path: str) -> str:
    """Use "/" separators so paths look the same whichever OS ingested them."""
    return path.replace("\\", "/")


def is_ignored_file(path: str) -> bool:
    """True for generated files (e.g. lock files) that should not be scored."""
    file_name = path.rsplit("/", 1)[-1]
    return file_name in IGNORED_FILE_NAMES


def is_bot(author_name: str, author_email: str) -> bool:
    """True for automated accounts such as "dependabot[bot]"."""
    return "[bot]" in author_name or "[bot]" in author_email


def score_files(contributions: list[Contribution]) -> list[FileOwnership]:
    """Compute ownership and risk for every file, riskiest first.

    Skips generated files, bot authors, and files with no lines added.
    """
    # lines_by_file[path][email] = total lines that author added to the file
    lines_by_file: dict[str, dict[str, int]] = defaultdict(lambda: defaultdict(int))

    # An email can appear with several names (e.g. "haradeep1" and
    # "Haradeep Puneti"). Show the name used for the most lines.
    lines_by_email_and_name: dict[str, dict[str, int]] = defaultdict(lambda: defaultdict(int))

    for row in contributions:
        path = normalize_path(row.file_path)
        if is_ignored_file(path) or is_bot(row.author_name, row.author_email):
            continue

        email = row.author_email.lower()
        lines_by_file[path][email] += row.lines_added
        lines_by_email_and_name[email][row.author_name] += row.lines_added

    display_name = {
        email: max(names, key=names.get) for email, names in lines_by_email_and_name.items()
    }

    results = []
    for path, lines_by_email in lines_by_file.items():
        total_lines = sum(lines_by_email.values())
        if total_lines == 0:
            continue  # e.g. binary files, which have no line counts

        authors = sorted(
            (
                AuthorShare(name=display_name[email], share=lines / total_lines)
                for email, lines in lines_by_email.items()
                if lines > 0
            ),
            key=lambda author: author.share,
            reverse=True,
        )
        top = authors[0]
        results.append(
            FileOwnership(
                path=path,
                risk_score=top.share,
                top_author=top.name,
                top_author_share=top.share,
                authors=authors,
            )
        )

    return sorted(results, key=lambda file: file.risk_score, reverse=True)
